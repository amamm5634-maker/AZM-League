import { computeAwards } from '../src/lib/awards';
import type { Match, TournamentState } from '../src/types';
const P = (id: string, teamId: string, position: string) => ({ id, teamId, position, name: id, number: 1 });
const players = [P('t01-p01', 't01', 'حارس'), P('t01-p02', 't01', 'مهاجم'), P('t02-p01', 't02', 'حارس'), P('t02-p02', 't02', 'مهاجم')];
const m = (id: string, status: string, h: number, a: number, motmId?: string): Match => ({ id, homeId: 't01', awayId: 't02', homeScore: h, awayScore: a, status, motmId } as Match);
const ev = (id: string, scorerId: string, teamId: string) => ({ id, matchId: 'm1', type: 'goal', teamId, scorerId });
const base = (over: Partial<TournamentState>) => ({ players, matches: [], events: [], lineups: [], ...over }) as unknown as TournamentState;
let bad = 0;
const t = (n: string, ok: boolean) => { if (!ok) { bad++; console.log('FAIL', n); } };
t('empty => none', Object.keys(computeAwards(base({}))).length === 0);
const s1 = base({ events: [ev('e1', 't01-p02', 't01'), ev('e2', 't01-p02', 't01'), ev('e3', 't02-p02', 't02')] as never });
const a1 = computeAwards(s1); t('scorer leader only', a1['t01-p02']?.includes('scorer') && !a1['t02-p02']);
const s2 = base({ events: [ev('e1', 't01-p02', 't01'), ev('e3', 't02-p02', 't02')] as never });
const a2 = computeAwards(s2); t('tie shares', a2['t01-p02']?.includes('scorer') && a2['t02-p02']?.includes('scorer'));
const s3 = base({ matches: [m('m1', 'completed', 1, 0, 't01-p02'), m('m2', 'completed', 0, 0, 't01-p02'), m('m3', 'completed', 0, 2, 't02-p02')] });
const a3 = computeAwards(s3); t('mvp most awards', a3['t01-p02']?.includes('mvp') && !a3['t02-p02']);
const lu = (matchId: string, teamId: string, gk: string) => ({ matchId, teamId, playerIds: [gk] });
const s4 = base({ matches: [m('m1', 'completed', 1, 0), m('m2', 'completed', 0, 0)], lineups: [lu('m1', 't01', 't01-p01'), lu('m1', 't02', 't02-p01'), lu('m2', 't01', 't01-p01'), lu('m2', 't02', 't02-p01')] as never });
const a4 = computeAwards(s4); t('keeper most clean sheets', a4['t01-p01']?.includes('keeper') && !a4['t02-p01']);
const s5 = base({ matches: [m('m1', 'live', 0, 0)], lineups: [lu('m1', 't01', 't01-p01')] as never });
t('live match no keeper award', !computeAwards(s5)['t01-p01']);
const s6 = base({ matches: [m('m1', 'completed', 2, 1)], lineups: [lu('m1', 't01', 't01-p01'), lu('m1', 't02', 't02-p01')] as never });
t('no clean sheet no keeper', Object.keys(computeAwards(s6)).length === 0);
console.log(bad ? `${bad} failed` : 'awards ok');
if (bad) throw new Error('awards check failed');
