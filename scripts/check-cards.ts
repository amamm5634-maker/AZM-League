import { planCard } from '../src/lib/cards';
import type { Match, MatchCard, Player } from '../src/types';
const match = { id: 'm01', homeId: 't01', awayId: 't02' } as Match;
const players = [{ id: 't01-p01', teamId: 't01' }, { id: 't02-p01', teamId: 't02' }] as Player[];
let bad = 0;
const t = (n: string, ok: boolean) => { if (!ok) { bad++; console.log('FAIL', n); } };
const inp = (kind: 'yellow' | 'red', playerId = 't01-p01', teamId = 't01', minute?: number) => ({ matchId: 'm01', teamId, playerId, kind, minute });
const y: MatchCard = { id: 'a', matchId: 'm01', teamId: 't01', playerId: 't01-p01', kind: 'yellow' };
const r: MatchCard = { ...y, id: 'b', kind: 'red' };
const p1 = planCard([], inp('yellow'), match, players); t('first yellow', p1.ok && p1.kinds.join() === 'yellow');
const p2 = planCard([y], inp('yellow'), match, players); t('second yellow => red', p2.ok && p2.kinds.join() === 'yellow,red');
const p3 = planCard([], inp('red'), match, players); t('direct red', p3.ok && p3.kinds.join() === 'red');
t('no card after red', !planCard([r], inp('yellow'), match, players).ok);
t('wrong team', !planCard([], inp('yellow', 't01-p01', 't02'), match, players).ok);
t('bad minute', !planCard([], inp('yellow', 't01-p01', 't01', 200), match, players).ok);
t('bad match', !planCard([], inp('yellow'), undefined, players).ok);
t('other player yellow stays single', (() => { const q = planCard([y], inp('yellow', 't02-p01', 't02'), match, players); return q.ok && q.kinds.join() === 'yellow'; })());
console.log(bad ? `${bad} failed` : 'cards ok');
if (bad) throw new Error("cards check failed");
