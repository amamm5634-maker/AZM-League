import { benchIds, canDeleteSub, onPitchIds, validateSub } from '../src/lib/subs';
import type { Lineup, Match, MatchCard, MatchSub, Player } from '../src/types';
const match = { id: 'm01', homeId: 't01', awayId: 't02' } as Match;
const squad = Array.from({ length: 18 }, (_, i) => ({ id: `t01-p${String(i + 1).padStart(2, '0')}`, teamId: 't01' })) as Player[];
const id = (n: number) => `t01-p${String(n).padStart(2, '0')}`;
const lineup: Lineup = { matchId: 'm01', teamId: 't01', playerIds: Array.from({ length: 11 }, (_, i) => id(i + 1)) };
let bad = 0;
const t = (n: string, ok: boolean) => { if (!ok) { bad++; console.log('FAIL', n); } };
const inp = (o: number, i: number, minute?: number) => ({ matchId: 'm01', teamId: 't01', outId: id(o), inId: id(i), minute });
const sub = (n: number, o: number, i: number): MatchSub => ({ id: `s${n}`, matchId: 'm01', teamId: 't01', outId: id(o), inId: id(i) });
t('valid', validateSub(inp(1, 12), match, lineup, [], [], squad) === null);
t('no lineup', validateSub(inp(1, 12), match, undefined, [], [], squad) !== null);
t('out not on pitch (bench)', validateSub(inp(12, 13), match, lineup, [], [], squad) !== null);
t('in is starter', validateSub(inp(1, 2), match, lineup, [], [], squad) !== null);
t('subbed-out cannot return', validateSub(inp(2, 1), match, lineup, [sub(1, 1, 12)], [], squad) !== null);
t('subbed-in can go out', validateSub(inp(12, 13), match, lineup, [sub(1, 1, 12)], [], squad) === null);
t('already used sub in cannot re-enter', validateSub(inp(2, 12), match, lineup, [sub(1, 1, 12)], [], squad) !== null);
const five = [sub(1, 1, 12), sub(2, 2, 13), sub(3, 3, 14), sub(4, 4, 15), sub(5, 5, 16)];
t('max 5', validateSub(inp(6, 17), match, lineup, five, [], squad) !== null);
const red: MatchCard = { id: 'c', matchId: 'm01', teamId: 't01', playerId: id(3), kind: 'red' };
t('red leaves pitch', !onPitchIds(lineup, [], [red], 'm01', 't01').includes(id(3)) && onPitchIds(lineup, [], [red], 'm01', 't01').length === 10);
t('sent-off cannot be subbed', validateSub(inp(3, 12), match, lineup, [], [red], squad) !== null);
t('bench size', benchIds(lineup, [sub(1, 1, 12)], squad, 'm01', 't01').length === 6);
t('bad minute', validateSub(inp(1, 12, 150), match, lineup, [], [], squad) !== null);
t('wrong team players', validateSub({ ...inp(1, 12), teamId: 't02' }, match, lineup, [], [], squad) !== null);
const chain = [sub(1, 1, 12), sub(2, 12, 13)];
t('delete blocked when built upon', !canDeleteSub(chain, chain[0]) && canDeleteSub(chain, chain[1]));
console.log(bad ? `${bad} failed` : 'subs ok');
if (bad) throw new Error('subs check failed');
